# List: preserves sequence order and allows duplicates
students = ["Ravi", "Priya", "Ravi"]
print("Students:", students)

# Set: stores unique elements
processed_ids = {101, 102, 101}
print("Unique IDs:", processed_ids)

# Dictionary: stores key-value pairs
student_details = {
    101: "Ravi",
    102: "Priya"
}
print("Student details:", student_details)